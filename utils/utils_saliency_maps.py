### LRP ###

def store_hook(module, input, output):
    """
    Hook function to store the output and gradients for the given module.
    """
    if isinstance(output, tuple):
        output = output[-1]
    module.output = output
    output.retain_grad()

def generate_lrp_heatmap(resnet, img_tensor, top_index, lrp_layer_names):
        """
        Generate LRP heatmap based on the specified layers in lrp_layer_names.
        
        Args:
            img_tensor (torch.Tensor): The input image tensor.
            top_index (int): The top predicted class index.

        Returns:
            np.ndarray: Heatmap generated by LRP.
        """
        grads = {}
        with EpsilonPlus(canonizers=[SequentialMergeBatchNorm()]).context(resnet) as modified_model:
            handles = [
                module.register_forward_hook(store_hook) for name, module in modified_model.named_modules()
                if name in lrp_layer_names
            ]

            output = modified_model(img_tensor)
            output[0, top_index].backward()

            for name, module in modified_model.named_modules():
                if name in lrp_layer_names:
                    grads[name] = module.output.grad

        for handle in handles:
            handle.remove()

        heatmap = grads[lrp_layer_names[0]].squeeze(0).cpu().detach().mean(dim=0).numpy()
        return np.maximum(heatmap, 0)


### SmoothGrad ###

def generate_smoothgrad_heatmap(model, img_tensor, top_index, stdev_spread=0.15, nsamples=25, magnitude=True):
    """
    Generate SmoothGrad heatmap.
    
    Args:
        model (torch.nn.Module): The model to explain.
        img_tensor (torch.Tensor): The input image tensor.
        top_index (int): The top predicted class index.
        stdev_spread (float): The standard deviation spread for generating noise.
        nsamples (int): The number of noisy samples to generate.
        magnitude (bool): Whether to compute the magnitude of the gradients.

    Returns:
        np.ndarray: SmoothGrad heatmap.
    """
    model.eval()  # Ensure the model is in evaluation mode

    stdev = stdev_spread * (torch.max(img_tensor) - torch.min(img_tensor))
    total_gradients = torch.zeros_like(img_tensor)

    # Explicitly enable gradient tracking
    with torch.set_grad_enabled(True):
        for i in range(nsamples):
            noise = torch.randn_like(img_tensor) * stdev
            noisy_image = img_tensor + noise
            noisy_image.requires_grad_()  # Ensure gradient tracking
            
            # Forward pass
            output = model(noisy_image)
            model.zero_grad()  # Zero out previous gradients
            
            # Backpropagate to get gradients for the predicted class
            loss = output[0, top_index]
            loss.backward()
            
            # Retrieve gradients
            grad = noisy_image.grad

            if grad is None:
                raise RuntimeError("Gradients were not computed. Ensure that `requires_grad` is set and model is in eval mode.")
            
            if magnitude:
                total_gradients += grad.abs()  # Accumulate absolute gradients
            else:
                total_gradients += grad

    avg_gradients = total_gradients / nsamples  # Average the accumulated gradients
    
    # Normalize the gradients for visualization
    smooth_grad = avg_gradients.squeeze().cpu().numpy()
    smooth_grad = (smooth_grad - smooth_grad.min()) / (smooth_grad.max() - smooth_grad.min())  # Normalize to [0, 1]
    
    return smooth_grad

### LayerCam ###

def generate_layercam_heatmap(model, img_tensor, top_index, target_layer, output_shape):
    """
    Generate a simple LayerCAM heatmap using torchcam's LayerCAM method.

    Args:
        model (torch.nn.Module): The model to explain.
        img_tensor (torch.Tensor): The input image tensor (e.g., with shape [1, 3, H, W]).
        top_index (int): The top predicted class index (the class for which to generate the heatmap).
        target_layer (str or torch.nn.Module): The target layer in the model to use for LayerCAM.
    
    Returns:
        np.ndarray: The resized LayerCAM heatmap.
    """
    # Initialize LayerCAM with the target layer
    cam_extractor = LayerCAM(model, target_layer=target_layer)

    # Ensure the model is in evaluation mode
    model.eval()

    # Perform a forward pass through the model
    output = model(img_tensor)

    # Generate the LayerCAM heatmap for the specific class index
    activation_map = cam_extractor(class_idx=top_index, scores=output)

    # Extract the first 2D heatmap from the batch (assuming single image)
    heatmap = activation_map[0].cpu().numpy()

    # Normalize heatmap to [0, 1] for visualization purposes (optional)
    heatmap = (heatmap - heatmap.min()) / (heatmap.max() - heatmap.min() + 1e-8)

    if heatmap.ndim == 3:  # Check if there are multiple channels
        heatmap = np.mean(heatmap, axis=-1)

    # Resize heatmap to match the output dimensions
    heatmap = cv2.resize(heatmap, (output_shape[1], output_shape[0]), interpolation=cv2.INTER_NEAREST)

    return heatmap