import matplotlib.pyplot as plt
import numpy as np
import math

import torch


def overlay_masks_on_image_gpu(image_shape, combined_mask, color=[1, 0, 0, 0.5]):
    """
    Overlay combined binary masks on an image with the specified color using GPU acceleration.

    Args:
        image_shape (tuple): Shape of the input image.
        combined_mask (torch.Tensor): Combined binary mask (on GPU).
        color (list): RGBA color for the mask.

    Returns:
        torch.Tensor: RGBA mask with masks overlaid (on GPU).
    """
    # Create an empty RGBA mask on GPU
    rgba_mask = torch.zeros((*image_shape[:2], 4), device=combined_mask.device)

    # Apply the color and alpha values
    rgba_mask[:, :, 3] = combined_mask * color[3]
    rgba_mask[:, :, 0] = combined_mask * color[0]
    rgba_mask[:, :, 1] = combined_mask * color[1]
    rgba_mask[:, :, 2] = combined_mask * color[2]

    return rgba_mask


def show_masks_gpu(masks, image_shape):
    """
    Display masks over an image using GPU acceleration.

    Args:
        masks (list): List of masks, each in the form of a torch.Tensor (on GPU).
        image_shape (tuple): Shape of the image to overlay masks on.
    """
    # Create an empty overlay on GPU
    overlay = torch.zeros((image_shape[0], image_shape[1], 4), device='cuda')

    # Overlay each mask with a random color
    for ann in masks:
        mask = torch.tensor(ann['segmentation'], dtype=torch.float32).cuda()
        color = [*np.random.random(3), 0.6]
        mask_overlay = overlay_masks_on_image_gpu(overlay.shape, mask, color)

        # Alpha blending
        alpha_mask = mask_overlay[:, :, 3:4]
        overlay[:, :, :3] = alpha_mask * mask_overlay[:, :, :3] + (1 - alpha_mask) * overlay[:, :, :3]
        overlay[:, :, 3] = torch.max(overlay[:, :, 3], mask_overlay[:, :, 3])

    # Move the overlay to CPU for displaying
    overlay_cpu = overlay.cpu().numpy()

    # Display the image
    ax = plt.gca()
    ax.imshow(overlay_cpu)


def display_results_side_by_side(image_rgb, heatmap, combined_image, combined_mask, ground_truth_mask, iou, dice):
    """
    Display the original image, the ResNet XAI heatmap, and the SAM masks side by side.

    Args:
        image_rgb (np.ndarray): The original RGB image.
        heatmap (np.ndarray): The heatmap generated by CAM.
        combined_image: Result of the combined and selected SAM masks.
        ground_truth_mask: The Ground truth mask from the PASCAL dataset.
        iou: The IoU score to display in the plot.
        dice: Dice Coeffiecient 
    """
    iou = iou * 100
    dice = dice * 100
    fig, axes = plt.subplots(1, 6, figsize=(20, 4))

    # Original image
    axes[0].imshow(image_rgb)
    axes[0].set_title("Original Image")
    axes[0].axis('off')

    # Image with heatmap
    axes[1].imshow(image_rgb)
    if heatmap.ndim == 3:
        heatmap = np.transpose(heatmap, (1, 2, 0))  # Transpose to (height, width, channels)
    axes[1].imshow(heatmap, cmap='Reds', alpha=0.8)
    axes[1].set_title("ResNet XAI Heatmap")
    axes[1].axis('off')

    # Image with combined SAM masks
    axes[2].imshow(combined_image)
    axes[2].set_title("Combined SAM Masks with image")
    axes[2].axis('off')

    # combined SAM mask
    axes[3].imshow(combined_mask, cmap='gray')
    axes[3].set_title('Combined SAM masks')
    axes[3].axis('off')

    # Ground truth mask
    axes[4].imshow(ground_truth_mask, cmap='gray')
    axes[4].set_title('Ground Truth Mask')
    axes[4].axis('off')

    # Display IoU and Dice scores as text
    axes[5].text(0.5, 0.6, f"IoU: {round(iou, 2)}%", ha='center', va='center', fontsize=14)
    axes[5].text(0.5, 0.4, f"Dice: {round(dice, 2)}%", ha='center', va='center', fontsize=14)
    axes[5].axis('off')

    plt.show()
    

def print_masks_in_grid_with_scores(image, masks, iou_scores, cols=10, base_width=3, base_height=3):
    """
    Print masks in a grid with their IoU scores.

    Args:
        image (np.ndarray): The original RGB image.
        masks (list): List of masks generated by SAM.
        iou_scores (list): List of IoU scores.
        cols (int): Number of columns in the grid.
        base_width (int): Base width of each subplot.
        base_height (int): Base height of each subplot.
    """
    rows = (len(masks) + cols - 1) // cols
    fig, axes = plt.subplots(rows, cols, figsize=(cols * base_width, rows * base_height))

    if rows == 1:
        axes = [axes]

    for idx, (mask, iou_score) in enumerate(zip(masks, iou_scores)):
        ax = axes[idx // cols][idx % cols] if rows > 1 else axes[idx]

        # Convert mask to torch tensor and move to GPU
        mask_tensor = torch.tensor(mask['segmentation'], dtype=torch.float32).cuda()

        # Create an image to display the mask with the overlay
        rgba_mask = overlay_masks_on_image_gpu(image.shape, mask_tensor, color=[1, 0, 0, 1])

        # Move the mask back to CPU for displaying
        rgba_mask_cpu = rgba_mask.cpu().numpy()

        # Display the mask in the corresponding subplot
        ax.imshow(image)
        ax.imshow(rgba_mask_cpu)
        ax.set_title(f"IoU: {iou_score:.6f}")
        ax.axis('off')

    for ax in axes.flatten():
        ax.axis('off')

    plt.tight_layout()
    plt.show()


def print_clusters_with_iou_scores(sorted_combined_masks, cluster_areas, cluster_scores):
    print("\nAll Clusters:")
    for idx, combined_mask in enumerate(sorted_combined_masks):
        area_percentage = cluster_areas[idx]
        weighted_iou = cluster_scores[idx]
        print(
            f"Cluster {idx + 1} (weighted IoU: {weighted_iou:.6f}, unique covered area: {area_percentage:.2f}%)")

    # Plot all clusters and their weighted IoU scores
    scores = [cluster_scores[idx] for idx in range(len(sorted_combined_masks))]
    plt.figure(figsize=(4, 2))
    plt.plot(range(len(scores)), scores, marker='o')
    plt.xlabel('Cluster Rank')
    plt.ylabel('Weighted IoU')
    plt.title('Cluster Weighted IoU Scores')
    plt.show()


def display_clusters_in_grid(image, sorted_combined_masks, cluster_areas, cluster_scores, cols=10):
    """
    Display clusters with masks highlighted on the background image in a grid.

    Args:
        image (np.ndarray): The original RGB image.
        sorted_combined_masks (list): List of combined masks (torch tensors).
        cluster_areas (dict): Dictionary of cluster areas.
        cluster_scores (dict): Dictionary of cluster scores.
        cols (int): Number of columns in the grid.
    """
    rows = (len(sorted_combined_masks) + cols - 1) // cols
    fig, axes = plt.subplots(rows, cols, figsize=(cols * 3, rows * 3))

    if rows == 1:
        axes = np.expand_dims(axes, 0)
    if cols == 1:
        axes = np.expand_dims(axes, 1)

    for idx, combined_mask in enumerate(sorted_combined_masks):
        # Overlay the combined mask on the image
        rgba_mask = overlay_masks_on_image_gpu(image.shape, combined_mask, color=[1, 0, 0, 0.5])

        # Move the mask back to CPU for displaying
        rgba_mask_cpu = rgba_mask.cpu().numpy()

        row, col = divmod(idx, cols)
        axes[row, col].imshow(image)
        axes[row, col].imshow(rgba_mask_cpu, alpha=0.9)
        axes[row, col].set_title(f"Area: {cluster_areas[idx]:.2f}%, IoU: {cluster_scores[idx]:.6f}")
        axes[row, col].axis('off')

    for ax in axes.flatten():
        ax.axis('off')

    plt.tight_layout()
    plt.show()


