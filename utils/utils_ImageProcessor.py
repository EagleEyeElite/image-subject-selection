import pandas as pd
import torch
from torch.nn import functional as F
import cv2

from .utils import img_to_cv2, imagenet_transform
from .utils_setup import choose_device
from .utils_resnet import get_result
from .utils_masks import evaluate_heatmap_alignment, return_selected_masks
from .utils_cluster import get_cluster, filter_clusters_by_elbow, return_combined_clusters
from .utils_data import extract_true_label

from segment_anything import SamAutomaticMaskGenerator

def process_sam_and_metrics(sam, image_rgb, heatmap, ground_truth_mask, metrics):
    """
    Generate SAM masks, align with the heatmap, cluster the results, and calculate evaluation metrics.
    
    Args:
        sam (SamAutomaticMaskGenerator): SAM mask generator model.
        image_rgb (np.ndarray): RGB image.
        heatmap (np.ndarray): The heatmap generated by the XAI method.
        ground_truth_mask (np.ndarray): The ground truth segmentation mask.
        metrics (dict): Dictionary of metric functions to calculate.
        
    Returns:
        dict: Dictionary containing the computed metric values.
    """
    # Generate SAM masks
    mask_generator = SamAutomaticMaskGenerator(
        model=sam,
        points_per_side=32,
        pred_iou_thresh=0.86,
        stability_score_thresh=0.92,
        crop_n_layers=1,
        crop_n_points_downscale_factor=2,
        min_mask_region_area=100
    )
    
    masks = mask_generator.generate(image_rgb)
    
    # Evaluate heatmap alignment
    sorted_iou_scores, sorted_masks = evaluate_heatmap_alignment(masks, heatmap)

    # Clustering and selecting masks
    sorted_combined_masks, cluster_areas, cluster_scores = get_cluster(sorted_masks, heatmap)
    relevant_clusters = filter_clusters_by_elbow(cluster_scores)
    combined_masks = return_selected_masks(relevant_clusters, sorted_combined_masks)

    combined_masks_resized = cv2.resize(combined_masks, (image_rgb.shape[1], image_rgb.shape[0]), interpolation=cv2.INTER_NEAREST)

    combined_image = return_combined_clusters(relevant_clusters, sorted_combined_masks, image_rgb)

    # Calculate all metrics
    metric_values = {metric_name: metric(combined_masks, ground_truth_mask)
                     for metric_name, metric in metrics.items()}

    return metric_values, combined_masks_resized

class ImageProcessor:
    def __init__(self, dataset, resnet, sam, imagenet_labels, xai_methods, metrics, pascal_labels):
        self.dataset = dataset
        self.resnet = resnet
        self.sam = sam
        self.imagenet_labels = imagenet_labels
        self.xai_methods = xai_methods
        self.pascal_labels = pascal_labels
        self.metrics = metrics

        # Initialize a list to accumulate all results
        self.all_results = []

        # Define all possible columns
        self.result_columns = ["dataset_idx", "xai_method", "true_label", "pred_label", 
                               "iou", "precision", "recall", "f1", "dice", "biou", 
                               "asd", "assd", "hd", "nsd"]


        

    def process_image(self, idx, visualization=False):
        """
        Process a single image using multiple XAI methods and compute evaluation metrics.
        
        Args:
            idx (int): The index of the image in the dataset.
            visualization (bool): Whether to return data for visualization.
        
        Returns:
            None or visualization_data: If visualization is True, returns the data required for visualization.
        """
        
        temp_results = []
        
        img, target = self.dataset[idx]

        image_rgb = img_to_cv2(img)
        ground_truth_mask = cv2.resize(img_to_cv2(target), (image_rgb.shape[1], image_rgb.shape[0]), interpolation=cv2.INTER_NEAREST)
    
        #ground_truth_mask = img_to_cv2(target)
        true_label = extract_true_label(target, self.pascal_labels)

        device = torch.device(choose_device())
        img_tensor = imagenet_transform(img).unsqueeze(0).to(device)

        pred = self.resnet(img_tensor).argmax()
        top_index = get_result(pred)
        pred_label = self.imagenet_labels[top_index]

        visualization_data = []

        for xai_method, method in self.xai_methods:
            heatmap = method(img_tensor, top_index)

            #Interpolation
            heatmap = torch.relu(heatmap)
            # normalize to [0, 1]
            heatmap = heatmap / heatmap.max()
            heatmap = F.interpolate(heatmap.view(1, 1, heatmap.shape[0], heatmap.shape[1]), size=img.size, mode="bilinear").view(img.size).cpu().numpy()
 
            metric_values, combined_mask = process_sam_and_metrics(self.sam, image_rgb, heatmap, ground_truth_mask, self.metrics)
            
            self.store_results(temp_results, idx, xai_method, pred_label, true_label, **metric_values)

            # If visualization is needed, collect the data
            if visualization:
                visualization_data.append({
                    "img": img,
                    "combined_mask": combined_mask,
                    "heatmap": heatmap,
                    "xai_method": xai_method,
                    "pred_label": pred_label,
                    "true_label": true_label,
                    "ground_truth_mask": ground_truth_mask,
                })

        # Append the results from this image to the main accumulation list
        self.all_results.extend(temp_results)

        # Return visualization data if needed
        if visualization:
            return visualization_data

    def store_results(self, temp_results, idx, method, pred_label, true_label, **metric_values):
        """
        Store the evaluation results for each XAI method in a temporary list.

        Args:
            temp_results (list): A list that temporarily stores the results for the current image being processed.
            idx (int): The dataset index of the image.
            method (str): The name of the XAI method used to generate the heatmap (e.g., 'GradCAM', 'LRP').
            pred_label (str): The predicted label from the model for the current image.
            true_label (str): The true label for the image (from the ground truth).
            **metric_values: A variable number of keyword arguments representing evaluation metrics (e.g., IoU, Dice, Precision, Recall, F1, etc.).

        Returns:
            None: The method appends a dictionary of results to the `temp_results` list, which will be accumulated into the main results DataFrame.
        """
        new_data = {
            "dataset_idx": idx,
            "xai_method": method,
            "true_label": true_label,
            "pred_label": pred_label,
            **metric_values
        }

        # Append the new result as a dictionary to the list
        temp_results.append(new_data)

    def get_final_results(self):
        """
        Convert the accumulated results to a DataFrame and return it.
        """
        # Convert the list of results to a DataFrame
        final_df = pd.DataFrame(self.all_results, columns=self.result_columns)
        return final_df
